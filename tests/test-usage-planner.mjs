import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ headless: true,
  ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : {}) })
try {
  const context = await browser.newContext({ offline: true })
  const page = await context.newPage()
  const requests = [], errors = []
  page.on('request', req => { if (/^https?:/.test(req.url())) requests.push(req.url()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(new URL('../docs/index.html', import.meta.url).href)
  const text = id => page.locator('#' + id).textContent()
  const fill = (id, amount) => page.locator('#' + id).fill(String(amount))
  const select = (id, value) => page.locator('#' + id).selectOption(value)
  const slider = page.getByRole('slider', { name: 'Applications per day' })
  assert.equal(await text('lite-tokens-week'), '90,000')
  assert.equal(await text('advanced-turns-week'), '150')
  assert.equal(await text('local-minutes-day'), '1 h 15 min')
  assert.equal(await page.locator('#model-rate').inputValue(), 'sol')
  assert.equal(await text('model-job'), '$0.012')
  assert.equal(await text('model-day'), '$0.06')
  assert.equal(await text('model-week'), '$0.30')
  assert.equal(await text('power-job'), '$0.0003634 to $0.0010902')
  assert.equal(await text('power-week'), '$0.009085 to $0.027255')
  await slider.focus()
  await slider.press('End')
  assert.equal(await text('count'), '50')
  await slider.press('Home')
  assert.equal(await text('lite-tokens-day'), '0')
  assert.equal(await text('power-week'), '$0.00')
  assert.equal(await text('model-week'), '$0.00')
  await slider.press('ArrowRight')
  await slider.press('ArrowRight')
  await select('days', '3')
  assert.equal(await text('week-count'), '6 applications in a planned week')
  assert.equal(await text('model-week'), '$0.072')
  await page.getByText('Adjust Lite assumptions', { exact: true }).click()
  await fill('lite-turns', 4)
  await fill('lite-tokens', 1250)
  await fill('lite-minutes', 10)
  assert.equal(await text('lite-turns-day'), '8')
  assert.equal(await text('lite-tokens-week'), '30,000')
  assert.equal(await text('lite-minutes-week'), '1 h')
  assert.equal(await text('advanced-turns-day'), '12')
  await fill('limit', 4)
  assert.match(await text('allow-result'), /200%/)
  await select('period', 'week')
  assert.equal(await page.locator('#limit').inputValue(), '')
  await fill('limit', 48)
  assert.match(await text('allow-result'), /24 of 48 turns · 50%/)
  await select('unit', 'tokens')
  await fill('limit', 100000)
  assert.match(await text('allow-result'), /30,000 of 100,000 tokens · 30%/)
  for (const [limit, expected] of [[29999, 'just over 100%'], [30000, '100%'], [30001, 'just under 100%']]) {
    await fill('limit', limit)
    assert.equal(await text('allow-result'), '30,000 of ' + limit.toLocaleString('en-US') + ' tokens · ' + expected + ' of this allowance.')
  }
  await select('period', 'custom')
  await fill('limit', 50000)
  assert.match(await text('allow-result'), /applications planned/)
  await fill('custom-count', 3)
  assert.match(await text('allow-result'), /15,000 of 50,000 tokens · 30%/)
  await select('workflow', 'advanced')
  assert.equal(await page.locator('#limit').inputValue(), '')
  await select('workflow', 'lite')
  assert.match(await text('allow-result'), /30%/)
  await fill('limit', 0)
  assert.match(await text('allow-result'), /positive whole number/)
  await fill('limit', 50000)
  await fill('lite-tokens', '')
  assert.equal(await text('lite-turns-day'), '—')
  assert.match(await text('allow-result'), /Complete the workflow/)
  await fill('lite-tokens', 1200)
  // Distinct counts catch swapped input/output rates and accidental aggregation by turn.
  await fill('job-input', 2000)
  await fill('job-output', 500)
  const allowance = await text('allow-result')
  for (const [model, unit, rateIn, rateOut, perJob, perWeek] of [
    ['sol', 'USD', 2, 10, '$0.009', '$0.054'],
    ['astra', 'USD', 8, 40, '$0.036', '$0.216'],
    ['luna', 'USD', 0.1, 0.5, '$0.00045', '$0.0027'],
    ['sonnet', 'USD', 2, 10, '$0.009', '$0.054'],
    ['neon', 'USD', 3, 15, '$0.0135', '$0.081'],
    ['sol-credits', 'credits', 50, 250, '0.225 credits', '1.35 credits'],
    ['astra-credits', 'credits', 200, 1000, '0.9 credits', '5.4 credits'],
  ]) {
    await select('model-rate', model)
    assert.equal(Number(await page.getByLabel('Input ' + unit + ' per 1M tokens', {exact:true}).inputValue()), rateIn)
    assert.equal(Number(await page.getByLabel('Output ' + unit + ' per 1M tokens', {exact:true}).inputValue()), rateOut)
    assert.equal(await text('model-job'), perJob)
    assert.equal(await text('model-week'), perWeek)
    assert.equal(await text('allow-result'), allowance)
  }
  await select('model-rate', 'custom')
  assert.equal(await text('model-week'), 'Unknown')
  await fill('input-rate', 0)
  assert.equal(await text('model-job'), 'Unknown')
  await fill('output-rate', 0)
  assert.equal(await text('model-week'), '$0.00')
  await fill('output-rate', 0.75)
  assert.equal(await text('model-day'), '$0.00075')
  await select('model-rate', 'sol-credits')
  assert.equal(await text('model-job'), '0.225 credits')
  await select('model-rate', 'custom')
  assert.equal(await text('model-job'), '$0.000375')
  await fill('output-rate', -1)
  assert.equal(await text('model-week'), 'Unknown')
  await select('model-rate', 'sol')
  await fill('job-input', 0.5)
  assert.equal(await text('model-job'), 'Unknown')
  await fill('job-input', 2000)

  await fill('watts', 125.5)
  await fill('min-runtime', 3)
  await fill('max-runtime', 3)
  await fill('electricity-rate', 0.20)
  assert.equal(await text('power-job'), '$0.001255')
  assert.equal(await text('power-day'), '$0.00251')
  assert.equal(await text('power-week'), '$0.00753')
  await fill('min-runtime', 3.5)
  assert.equal(await text('power-job'), 'Unknown')
  assert.equal(await page.locator('#power-error').isVisible(), true)
  await fill('max-runtime', 6)
  assert.equal(await text('power-job'), '$0.0014642 to $0.00251')
  assert.equal(await page.locator('#power-error').isVisible(), false)
  await fill('electricity-rate', '')
  assert.equal(await text('power-week'), 'Unknown')
  await fill('electricity-rate', 0)
  assert.equal(await text('power-week'), '$0.00')
  assert.equal(await text('model-job'), '$0.009')
  for (const width of [320, 390, 1056]) {
    await page.setViewportSize({ width, height: 800 })
    const fits = await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)
    assert.ok(fits, 'Layout fits at ' + width + 'px')
  }
  if (process.env.PLANNER_SCREENSHOT) await page.screenshot({ path: process.env.PLANNER_SCREENSHOT, fullPage: true })
  await page.reload()
  assert.equal(await page.locator('#limit').inputValue(), '')
  assert.deepEqual(requests, [])
  assert.deepEqual(errors, [])
  console.log('Offline planner passed: workload, allowances, API dollars, Codex credits, electricity, overrides and layout.')
} finally {
  await browser.close()
}
